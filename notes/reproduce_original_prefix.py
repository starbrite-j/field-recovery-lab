"""Export exact samples of the named original's initial region.

Run with Python's standard library. No value is assigned to the unknown P.
The output contains exact U and E/P at x=t^10; it is not a full numerical
reproduction. PrefixSampleCertificate.lean independently checks every sample
against OriginalFieldReproduction.lean, using the repository's Lean toolchain.

    python3 notes/reproduce_original_prefix.py
    python3 notes/reproduce_original_prefix.py --check
    python3 notes/verify_recovery.py
"""

from __future__ import annotations

import argparse
from fractions import Fraction
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SOURCE_COMMIT = 'f9e8bc5b38b6e212696e8a30e3e91517af887bbd'
T_VALUES = tuple(Fraction(1, 10**i) for i in range(5))
ETA_VALUES = tuple(Fraction(i, 4) for i in range(-4, 5))


def rational(value: Fraction) -> dict[str, str]:
    # Strings preserve large exact integers when read by JavaScript clients.
    return {'numerator': str(value.numerator), 'denominator': str(value.denominator)}


def lean_number(value: Fraction) -> str:
    if value.denominator == 1:
        return str(value.numerator)
    return f'({value.numerator} / {value.denominator})'


def outputs() -> dict[Path, str]:
    grid = [
        {'x': t**10, 't': t, 'eta': eta,
         'e_over_p': t / (1 + eta**2), 'u': 4 * eta}
        for t in T_VALUES for eta in ETA_VALUES
    ]
    sample_document = {
        'format': 'exact-original-prefix-v1',
        'upstream_commit': SOURCE_COMMIT,
        'source_profile': 'NavierStokes.PreparedOutgoing.prepared.profile',
        'full_numerical_reproduction': False,
        'actual_observed_dataset_used': False,
        'region': '0 < x <= 1, -1 <= eta <= 1',
        'formula': {'E': 'P * x^(1/10) / (1 + eta^2)', 'U': '4 * eta'},
        'unknown_source_amplitude': 'P = original.data.core.P; no numerical value assigned',
        'encoding': 'Each rational has decimal-string numerator and positive denominator.',
        'sample_count': len(grid),
        'certificate': 'notes/PrefixSampleCertificate.lean: all_samples',
        'verification_status_source': 'notes/verification/proof_verification.json',
        'samples': [{key: rational(value) for key, value in row.items()} for row in grid],
    }
    records = []
    for row in grid:
        entries = ', '.join(
            f'{name} := {lean_number(row[key])}'
            for name, key in [('x', 'x'), ('t', 't'), ('eta', 'eta'),
                              ('eOverP', 'e_over_p'), ('u', 'u')]
        )
        records.append('  { ' + entries + ' }')
    certificate = '''import notes.OriginalFieldReproduction

/-!
Generated by notes/reproduce_original_prefix.py. Lean checks these exact
rationals against the source-prefix recovery theorem, independently of Python
arithmetic. E retains the named original's unknown amplitude P. These samples
cover the initial region only, not the reset, heating, or full radial domain.
-/

noncomputable section
open Set

namespace NavierStokes.PrefixSampleCertificate

structure Sample where
  x : ℝ
  t : ℝ
  eta : ℝ
  eOverP : ℝ
  u : ℝ

def samples : List Sample := [
''' + ',\n'.join(records) + ''']

def Certified (s : Sample) : Prop :=
  s.x = s.t ^ (10 : ℕ) ∧ 0 < s.t ∧ s.t ≤ 1 ∧
  s.eta ∈ HeatedOutgoing.parameterDomain ∧
  OriginalFieldReproduction.reproducedE (s.x, s.eta) =
    OriginalFieldReproduction.original.data.core.P * s.eOverP ∧
  OriginalFieldReproduction.reproducedE (s.x, s.eta) /
    OriginalFieldReproduction.original.data.core.P = s.eOverP ∧
  OriginalFieldReproduction.reproducedU (s.x, s.eta) = s.u

private theorem certify (s : Sample) (hx : s.x = s.t ^ (10 : ℕ))
    (ht : 0 < s.t) (ht1 : s.t ≤ 1)
    (heta : s.eta ∈ HeatedOutgoing.parameterDomain)
    (he : OutgoingSchedule.shape s.eta * s.t = s.eOverP)
    (hu : 4 * s.eta = s.u) : Certified s := by
  refine ⟨hx, ht, ht1, heta, ?_, ?_, ?_⟩
  · rw [hx, OriginalFieldReproduction.reproducedE_prefix s.t s.eta ht ht1 heta,
      mul_assoc, he]
  · rw [hx, OriginalFieldReproduction.reproducedE_prefix_normalized s.t s.eta ht ht1 heta,
      he]
  · rw [hx, OriginalFieldReproduction.reproducedU_prefix s.t s.eta ht ht1 heta, hu]

theorem all_samples : ∀ s ∈ samples, Certified s := by
  intro s hs
  simp only [samples, List.mem_cons, List.not_mem_nil, or_false] at hs
  rcases hs with ''' + ' | '.join('rfl' for _ in grid) + '''
  all_goals apply certify <;>
    norm_num [OutgoingSchedule.shape, HeatedOutgoing.parameterDomain, Set.mem_Icc]

end NavierStokes.PrefixSampleCertificate
'''
    return {
        ROOT / 'notes/original_field/prefix_samples.json': json.dumps(sample_document, indent=2) + '\n',
        ROOT / 'notes/PrefixSampleCertificate.lean': certificate,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check saved output without changing files.')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f'Generated output differs: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
        print(f'{"checked" if args.check else "wrote"} {path.relative_to(ROOT)} '
              f'sha256={hashlib.sha256(content.encode()).hexdigest()}')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
